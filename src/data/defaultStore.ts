import { StoreState, MenuItem } from '../types/store';

function enrichProduct(
  raw: Omit<
    MenuItem,
    | 'ingredients'
    | 'preparationSteps'
    | 'supportsHot'
    | 'supportsCold'
    | 'defaultTemp'
    | 'sizes'
    | 'recipe'
    | 'isBestseller'
    | 'isNewArrival'
    | 'ratingAvg'
    | 'reviewCount'
    | 'popularityScore'
  > &
    Partial<MenuItem>
): MenuItem {
  const isColdDefault =
    raw.id === 'cold-coffee' || raw.id === 'iced-coffee';
  const supportsCold =
    raw.supportsCold ??
    (isColdDefault ||
      raw.id === 'lemon-tea' ||
      raw.id === 'green-tea' ||
      raw.id === 'cafe-latte' ||
      raw.id === 'mocha' ||
      raw.id === 'black-coffee');
  const supportsHot = raw.supportsHot ?? !isColdDefault;

  const defaultRecipe: Record<string, number> =
    raw.category === 'tea'
      ? {
          'ing-tea-leaves': 6,
          'ing-milk':
            raw.id === 'lemon-tea' ||
            raw.id === 'green-tea' ||
            raw.id === 'kashmiri-kahwa'
              ? 0
              : 120,
          'ing-sugar': 10,
          ...(raw.id.includes('masala') || raw.id.includes('adrak') || raw.id === 'cutting-chai'
            ? { 'ing-ginger': 5 }
            : {}),
          ...(raw.id.includes('masala') ||
          raw.id.includes('elaichi') ||
          raw.id.includes('kesar') ||
          raw.id === 'kashmiri-kahwa'
            ? { 'ing-cardamom': 2 }
            : {}),
          ...(raw.id.includes('kesar') || raw.id === 'kashmiri-kahwa'
            ? { 'ing-saffron': 1 }
            : {}),
          ...(raw.id.includes('kulhad') || raw.id.includes('tandoori')
            ? { 'ing-kulhad': 1 }
            : {}),
          ...(raw.id === 'tulsi-chai' ? { 'ing-tulsi': 4 } : {}),
          ...(raw.id === 'lemon-tea' ? { 'ing-lemon': 1 } : {}),
        }
      : {
          'ing-coffee-beans': raw.id === 'instant-coffee' ? 8 : 16,
          'ing-milk':
            raw.id === 'espresso' || raw.id === 'black-coffee' ? 0 : 140,
          'ing-sugar': raw.id === 'espresso' || raw.id === 'black-coffee' ? 0 : 10,
          ...(raw.id === 'mocha' ? { 'ing-cocoa': 12 } : {}),
        };

  return {
    ...raw,
    supportsHot,
    supportsCold,
    defaultTemp: isColdDefault ? 'cold' : 'hot',
    sizes: raw.sizes ?? [
      { name: 'Small', volumeLabel: '120 ml', priceDelta: -10 },
      { name: 'Medium', volumeLabel: '180 ml', priceDelta: 0 },
      { name: 'Large', volumeLabel: '260 ml', priceDelta: 25 },
    ],
    ingredients:
      raw.ingredients ??
      (raw.category === 'tea'
        ? ['Upper Assam / Estate Tea Leaves', 'Filtered Water', 'Fresh Milk (if milk chai)', 'Whole Indian Spices']
        : ['Chikmagalur / Coorg Estate Coffee Beans', 'Filtered Water', 'Fresh Milk (where applicable)']),
    preparationSteps:
      raw.preparationSteps ??
      (raw.category === 'tea'
        ? 'Freshly crushed Indian spices simmered with whole tea leaves in brass vessel, strained piping hot into your chosen vessel.'
        : 'Freshly ground Indian estate coffee extracted to order and blended smoothly with steamed or chilled milk.'),
    recipe: raw.recipe ?? defaultRecipe,
    isBestseller:
      raw.isBestseller ??
      ['masala-chai', 'kulhad-chai', 'tandoori-chai', 'south-indian-filter-coffee', 'cold-coffee'].includes(
        raw.id
      ),
    isNewArrival:
      raw.isNewArrival ??
      ['kashmiri-kahwa', 'kesar-chai', 'iced-coffee'].includes(raw.id),
    ratingAvg: raw.ratingAvg ?? (raw.featured ? 4.9 : 4.7),
    reviewCount: raw.reviewCount ?? (raw.featured ? 2 : 1),
    popularityScore: raw.popularityScore ?? (raw.featured ? 96 : 82 - raw.sortOrder),
  };
}

